// flatten the svg shapes into one path string for Path2D
// the first 'm' is absolute but turns relative once joined, so make it 'M' and the implicit pairs 'l'
const NUM = '-?(?:\\d*\\.\\d+|\\d+\\.?)';

function absStart(d) {
  const m = new RegExp(`^\\s*m\\s*(${NUM})[\\s,]*(${NUM})([\\s\\S]*)$`).exec(d);
  if (!m) return d;
  const rest = m[3];
  return `M${m[1]} ${m[2]}` + (new RegExp(`^[\\s,]*${NUM}`).test(rest) ? 'l' + rest : rest);
}

function toPath(inner) {
  const out = [];

  for (const el of inner.match(/<(?:path|circle|rect|line|polyline|polygon)\b[^>]*>/g) || []) {
    const tag = /^<(\w+)/.exec(el)[1];
    const a = n => (new RegExp(`\\b${n}="([^"]*)"`).exec(el) || [])[1];
    const f = n => parseFloat(a(n) || 0);

    if (tag === 'path') out.push(absStart(a('d')));
    else if (tag === 'circle') {
      const cx = f('cx');
      const cy = f('cy');
      const r = f('r');
      out.push(`M${cx - r} ${cy}a${r} ${r} 0 1 0 ${2 * r} 0a${r} ${r} 0 1 0 ${-2 * r} 0`);
    } else if (tag === 'rect') {
      const x = f('x');
      const y = f('y');
      const w = f('width');
      const h = f('height');
      const r = Math.min(f('rx') || 0, w / 2, h / 2);
      out.push(
        r
          ? `M${x + r} ${y}h${w - 2 * r}a${r} ${r} 0 0 1 ${r} ${r}v${h - 2 * r}a${r} ${r} 0 0 1 ${-r} ${r}h${-(w - 2 * r)}a${r} ${r} 0 0 1 ${-r} ${-r}v${-(h - 2 * r)}a${r} ${r} 0 0 1 ${r} ${-r}z`
          : `M${x} ${y}h${w}v${h}h${-w}z`,
      );
    } else if (tag === 'line') out.push(`M${f('x1')} ${f('y1')}L${f('x2')} ${f('y2')}`);
    else {
      const n = a('points').trim().split(/[\s,]+/).map(Number);
      out.push(
        n.reduce((s, v, i) => s + (i % 2 ? ` ${v}` : `${i ? 'L' : 'M'}${v}`), '')
          + (tag === 'polygon' ? 'z' : ''),
      );
    }
  }

  return out.join('');
}

